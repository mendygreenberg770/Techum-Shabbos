/**
 * Reference dinim around leaving the techum. These simanim (397,
 * 404-407) are extant in the Alter Rebbe's Shulchan Aruch, so the
 * citations are to Shulchan Aruch HaRav.
 */
export default function BeyondTechumNotes() {
  return (
    <details className="checklist">
      <summary>If one went beyond the techum (SA HaRav 405–407)</summary>
      <ul>
        <li>
          One who walked beyond his techum — even deliberately — may move
          only within <b>4 amos</b> of where he stands (SA HaRav 405).
        </li>
        <li>
          Went out (or was taken out) <b>against his will and returned</b>:
          it is as if he never left (SA HaRav 405).
        </li>
        <li>
          Taken against his will into <b>another town enclosed by
          mechitzos</b>: the entire town is as his 4 amos (SA HaRav 405).
        </li>
        <li>
          One who left <b>with authorization</b> — to save a life, a midwife,
          and the like — has 2,000 amos from where he is, and all who go out
          to rescue may return to their place (SA HaRav 407).
        </li>
        <li>
          <b>Human dignity:</b> one needing to relieve himself may move
          until he finds a fitting private spot (SA HaRav 406).
        </li>
        <li>
          A person's <b>animals and belongings</b> share their owner's
          techum (SA HaRav 397).
        </li>
        <li>
          Travel <b>above 10 tefachim</b> (e.g., by boat) involves a safek
          whether techumin apply at all (SA HaRav 404) — consult a rav.
        </li>
      </ul>
    </details>
  );
}
